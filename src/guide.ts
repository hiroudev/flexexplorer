export const GUIDE_MD = `
## 1. 作業台を丸ごと保存する — ワークスペース

案件ごとに「どのフォルダをどう並べていたか」を保存できます。

1. ペインを好きな数だけ開いて、フォルダを表示する
2. **Ctrl+Shift+S** → 名前を付けて保存
3. 次からは一覧から選ぶだけで、その配置が丸ごと戻る

- **☆ を付けた1つは、起動時に自動で開きます。** 毎朝同じ配置から始めたいならこれ。
- **🪟 で新しいウィンドウに開けます。** 今の作業を崩さずに別案件を見たいときに。
- 「更新」で、今の状態を同じ名前に上書きできます。

> レイアウトグループ（ツールバーのタブ）は、ワークスペースの中でさらに配置を束ねる単位です。「調査用」「納品用」のようにグループを分けておくと **Ctrl+PageUp / PageDown** で行き来できます。

## 2. 年度・案件を切り替える — パンくずの ▼

同じ構造のフォルダが年度ごとに並んでいるとき、上まで戻って辿り直す必要はありません。

\`\`\`
\\\\共有\\案件\\10:2026\\10:基本設計\\成果物
                ↓  「10:2026」の ▼ から「20:2027」を選ぶ
\\\\共有\\案件\\20:2027\\10:基本設計\\成果物
\`\`\`

**下の階層はそのまま維持**されます。一覧の印で、切り替え先が同じ構造を持っているか分かります。

| 印 | 意味 |
|---|---|
| ● | 下の階層がすべてある |
| ◐ | 途中まである |
| ○ | 同じ構造がない |

○ や ◐ も選べます。その場合は**実在する一番深い階層まで**移動します（これから作るフォルダのこともあるため）。

## 3. 最新版がどれか一目で分かる — 世代ファイル

ツールバーの **🏷 最新版** を押すと、同じ資料の版が並んでいるフォルダで、**最も新しいものに色が付きます**。

\`\`\`
  A_20260818.xlsx
  A_20260818a.xlsx
● A_20260818a_02.xlsx   ← 色が付く
  B_20260818_01.xlsx
● B_20260901_01.xlsx    ← 別のセットとして判定
\`\`\`

ファイル名から数字（末尾の英字1文字まで含む）を取り除いて同じになるものを1セットと見なします。設定なしでこの形は動きます。

うまく括られないときは **設定 > 世代ファイル** で正規表現のルールを足せます。**表示中のフォルダに対する判定結果がその場でプレビューされる**ので、正規表現を書かなくても結果で確認できます。

## 4. 場所を一瞬で開く — パスの貼り付け

**Ctrl+Shift+V** で、クリップボードのパスを開きます。**ファイルを指していれば、そのフォルダを開いて、そのファイルを選択した状態**にします。

チャットやメールから貼るときの、こういう形もそのまま解釈します。

\`\`\`
\\\\hoge\\fuga
└ ファイル名.xlsx
\`\`\`

罫線（└ ┗ ├ │ ─ など）、改行、前後の引用符やスペースは自動で除去します。

同じことは **Ctrl+L**（アドレスバー）、**Ctrl+G**（GoTo）、**Ctrl+Alt+O**（クイックオープン）に貼っても起きます。

## 5. 他のアプリを開いたまま呼び出す — グローバルホットキー

**Ctrl+Alt+O** は、FlexExplorer がバックグラウンドにいても効きます。パスを入力すると \`tmp\` グループの新しいペインで開きます。

- BlueWind などのランチャや Win+R からフォルダを開いたときも、新しいウィンドウを作らず**実行中のウィンドウの \`tmp\` グループ**に追加されます。
- そのフォルダが既に \`tmp\` にあれば、増やさずにそこへ移動します。

調べもので開いたフォルダが本来の作業配置を汚さないので、あとで \`tmp\` グループごと閉じれば片付きます。

## 6. 他のアプリへファイルを渡す — Alt+ドラッグ

ファイルを **Alt を押しながらドラッグ**すると、メールや Slack など**他のアプリへ**ドロップできます。

Alt なしの通常のドラッグは、これまでどおり FlexExplorer 内での移動・コピーです。

- 同じドライブ内 → 移動、別ドライブ → コピー
- **Ctrl** を押しながらでコピー固定、**Shift** で移動固定
- フォルダの行に落とせばその中へ、リストの空白に落とせば表示中のフォルダへ

> Alt+ドラッグの最中はウィンドウの描画が止まります（OS の仕様）。ドロップすれば戻ります。

## 7. フォルダに私物のメモを貼る — 付箋メモ

**Ctrl+M** で、今見ているフォルダに付箋を貼れます。

**メモはそのフォルダの中には作られません。** 自分の PC にだけ保存されるので、共有フォルダでも、読み取り専用のフォルダでも使えます。他の人には見えません。

「この案件の連絡先」「ここのファイルは触るな」といった申し送りに。

## 8. 大量のファイルを片付ける — 一括リネーム

複数選択して **Ctrl+Shift+R**。置換・連番・日付・接頭辞などのルールを重ねられ、**適用前に結果が一覧で確認できます**。

単発なら **F2**（選択済みの行をゆっくり2回クリックでも可）でその場で名前を変えられます。

1つのファイルを日付付きで複製したいだけなら、右クリック > **コピーを日付付きで保存**が速いです。

## 9. 手に馴染ませる

- **ショートカットは全部変えられます。** 設定 > ショートカット。47個のアクションすべてに割り当て可能です。
- **Ctrl+Shift+P** のコマンドパレットから、名前で機能を探して実行できます。
- **Space** でインスペクター。画像・PDF・Markdown・テキスト・Excel の中身をその場で確認できます。
- **Ctrl+1〜9** でタブを直接選択、**Ctrl+←/→** でタブ移動。
- よく使うタブは**ピン留め**しておくと、🧹（ピン留め以外を閉じる）で巻き込まれません。
- ペインの境界はドラッグで動かせます。**隣のペインとの境界は一直線に揃ったまま**動きます。

## 10. 外部ツールと繋ぐ

インストールされていれば、右クリックから直接呼べます。

- **TortoiseSVN** — 更新・コミット・ログ・差分
- **WinMerge** — 2つ選んで比較
- **VS Code** / **ターミナル** — このフォルダで開く
- **管理者として実行** — Program Files 配下などを触るとき
- **Windows のメニューを表示…** — エクスプローラー本来の右クリックメニュー（送る、7-Zip、クラウド同期など）
`
